export function getDevotionalForDate(date: Date = new Date()): DailyDevotionalEntry {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diffTime = Math.abs(date.getTime() - startOfYear.getTime());
  const dayOfYear = Math.floor(diffTime / (1000 * 60 * 60 * 24)) + 1;

  const index = (dayOfYear - 1) % CURATED_DAILY_VERSES.length;
  return CURATED_DAILY_VERSES[index];
}
